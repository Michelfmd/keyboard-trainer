def translate(language: str, text: str, **values: object) -> str:
    template = SPANISH.get(text, text) if language == "es" else text
    return template.format(**values) if values else template


def tr(widget: tk.Misc, text: str, **values: object) -> str:
    return translate(getattr(widget.winfo_toplevel(), "language", "en"), text, **values)
